#!/usr/bin/env bash
# Bootstrap the project-local Android toolchain used for APK iteration.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS_DIR="${WINLATOR_TOOLS_DIR:-$ROOT_DIR/.tools}"
JDK_DIR="$TOOLS_DIR/jdk-17"
SDK_DIR="$TOOLS_DIR/android-sdk"
CMDLINE_TOOLS_DIR="$SDK_DIR/cmdline-tools/latest"
ENV_FILE="$TOOLS_DIR/env.sh"
JDK_URL="${WINLATOR_JDK_URL:-https://api.adoptium.net/v3/binary/latest/17/ga/linux/x64/jdk/hotspot/normal/eclipse}"
CMDLINE_TOOLS_URL="${WINLATOR_CMDLINE_TOOLS_URL:-https://dl.google.com/android/repository/commandlinetools-linux-13114758_latest.zip}"
NDK_VERSION="22.1.7171670"

die() { echo "[setup-dev] $*" >&2; exit 1; }
need_cmd() { command -v "$1" >/dev/null 2>&1 || die "Missing required command: $1"; }

for cmd in curl tar python3; do need_cmd "$cmd"; done
mkdir -p "$TOOLS_DIR" "$SDK_DIR"

if [[ ! -x "$JDK_DIR/bin/java" ]]; then
  archive="$TOOLS_DIR/temurin-17.tar.gz"
  echo "[setup-dev] Downloading JDK 17..."
  curl --fail --location --retry 3 --output "$archive" "$JDK_URL"
  rm -rf "$JDK_DIR"
  mkdir -p "$JDK_DIR"
  tar -xzf "$archive" --strip-components=1 -C "$JDK_DIR"
fi

if [[ ! -x "$CMDLINE_TOOLS_DIR/bin/sdkmanager" ]]; then
  archive="$TOOLS_DIR/android-commandline-tools.zip"
  stage="$TOOLS_DIR/android-commandline-tools-stage"
  echo "[setup-dev] Downloading Android command-line tools..."
  curl --fail --location --retry 3 --output "$archive" "$CMDLINE_TOOLS_URL"
  rm -rf "$stage" "$CMDLINE_TOOLS_DIR"
  mkdir -p "$stage" "$CMDLINE_TOOLS_DIR"
  # Python is used only as a ZIP extractor so bootstrap does not require sudo/apt.
  python3 -m zipfile -e "$archive" "$stage"
  mv "$stage/cmdline-tools"/* "$CMDLINE_TOOLS_DIR/"
  rmdir "$stage/cmdline-tools" "$stage"
fi

# zipfile deliberately does not restore Unix execute bits.
chmod +x "$CMDLINE_TOOLS_DIR/bin"/*

export JAVA_HOME="$JDK_DIR"
export ANDROID_SDK_ROOT="$SDK_DIR"
export ANDROID_HOME="$SDK_DIR"
export PATH="$CMDLINE_TOOLS_DIR/bin:$SDK_DIR/platform-tools:$PATH"

# `yes` receives SIGPIPE once sdkmanager has accepted every license. Temporarily
# disable pipefail so that normal completion is not mistaken for an error.
set +o pipefail
yes | sdkmanager --sdk_root="$SDK_DIR" --licenses >/dev/null
sdkmanager_license_status=${PIPESTATUS[1]}
set -o pipefail
[[ "$sdkmanager_license_status" -eq 0 ]] || die "Could not accept Android SDK licenses"
sdkmanager --sdk_root="$SDK_DIR" \
  "platform-tools" \
  "platforms;android-36" \
  "build-tools;30.0.3" \
  "build-tools;36.0.0" \
  "ndk;$NDK_VERSION" \
  "cmake;3.22.1"

for required in \
  "$SDK_DIR/platform-tools/adb" \
  "$SDK_DIR/platforms/android-36/android.jar" \
  "$SDK_DIR/build-tools/36.0.0/aapt2" \
  "$SDK_DIR/build-tools/30.0.3/aapt" \
  "$SDK_DIR/ndk/$NDK_VERSION/build/cmake/android.toolchain.cmake" \
  "$SDK_DIR/cmake/3.22.1/bin/cmake"; do
  [[ -e "$required" ]] || die "SDK package installation did not provide: $required"
done

mkdir -p "$TOOLS_DIR"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-dev.sh. Source this from an interactive shell.
export JAVA_HOME="$JDK_DIR"
export ANDROID_SDK_ROOT="$SDK_DIR"
export ANDROID_HOME="$SDK_DIR"
export ANDROID_NDK_HOME="$SDK_DIR/ndk/$NDK_VERSION"
export AARCH64_CC="\$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/bin/aarch64-linux-android26-clang"
export PATH="\$JAVA_HOME/bin:\$ANDROID_SDK_ROOT/platform-tools:\$PATH"
EOF
printf 'sdk.dir=%s\n' "$SDK_DIR" > "$ROOT_DIR/local.properties"

echo "[setup-dev] Ready. Run: source $ENV_FILE"
"$JDK_DIR/bin/java" -version 2>&1 | head -n 1
"$SDK_DIR/platform-tools/adb" version | head -n 1
